// Validates google-play-store-assets/ against Google Play's graphic requirements and the listing
// text limits, then writes google-play-store-assets/VALIDATION-REPORT.md. Exit code 1 on any FAIL.
// Run from the repository root:  node mobile/maytha_market/store/source/validate-assets.mjs
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../../../../google-play-store-assets");
const MB = 1024 * 1024;
const rows = [];
const add = (file, check, ok, detail) => rows.push({ file, check, ok, detail });

const format = (buf) => {
  if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return "png";
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpeg";
  return "unknown";
};

const hashes = new Map();
async function checkImage(rel, { width, height, maxBytes, noAlpha, ratio, minSide, maxSide }) {
  const p = path.join(dir, rel);
  if (!fs.existsSync(p)) return add(rel, "exists", false, "missing");
  add(rel, "exists", true, "");
  const buf = fs.readFileSync(p);
  const fmt = format(buf);
  add(rel, "format (magic bytes)", fmt !== "unknown", fmt);
  add(rel, "file size", buf.length > 0 && buf.length <= maxBytes, `${(buf.length / 1024).toFixed(0)} KB ≤ ${maxBytes / MB} MB`);
  let meta;
  try {
    meta = await sharp(buf).metadata();
    const st = await sharp(buf).stats();
    add(rel, "decodes, not blank", st.channels.some((c) => c.stdev > 1), `stdev ${st.channels[0].stdev.toFixed(1)}`);
  } catch (e) {
    return add(rel, "decodes", false, String(e));
  }
  if (width) add(rel, "exact dimensions", meta.width === width && meta.height === height, `${meta.width}x${meta.height} (want ${width}x${height})`);
  if (minSide) {
    const s = [meta.width, meta.height];
    add(rel, "side length", s.every((v) => v >= minSide && v <= maxSide), `${meta.width}x${meta.height}, sides ${minSide}-${maxSide}`);
  }
  if (ratio) {
    add(rel, "portrait 9:16", meta.height > meta.width && meta.width * 16 === meta.height * 9, `${meta.width}x${meta.height}`);
  }
  if (noAlpha) add(rel, "no alpha channel", !meta.hasAlpha, `channels ${meta.channels}`);
  const h = crypto.createHash("sha256").update(buf).digest("hex");
  add(rel, "unique (sha256)", !hashes.has(h), hashes.has(h) ? `duplicate of ${hashes.get(h)}` : h.slice(0, 12));
  hashes.set(h, rel);
}

await checkImage("icon/MAYTHA_icon_512x512.png", { width: 512, height: 512, maxBytes: 1 * MB });
await checkImage("feature-graphic/MAYTHA_feature_1024x500.png", { width: 1024, height: 500, maxBytes: 15 * MB, noAlpha: true });

const phoneDir = path.join(dir, "phone-screenshots");
const phones = fs.existsSync(phoneDir) ? fs.readdirSync(phoneDir).filter((f) => /\.(png|jpe?g)$/i.test(f)).sort() : [];
add("phone-screenshots/", "count 2..8 (target 8)", phones.length >= 2 && phones.length <= 8, `${phones.length} files`);
add("phone-screenshots/", "exactly 8 provided", phones.length === 8, `${phones.length}`);
for (const f of phones) {
  await checkImage(`phone-screenshots/${f}`, { width: 1080, height: 1920, maxBytes: 8 * MB, ratio: true, noAlpha: true, minSide: 320, maxSide: 3840 });
}

for (const t of ["tablet-7-inch", "tablet-10-inch"]) {
  const imgs = fs.existsSync(path.join(dir, t)) ? fs.readdirSync(path.join(dir, t)).filter((f) => /\.(png|jpe?g)$/i.test(f)) : [];
  add(`${t}/`, "optional; not produced (README explains)", imgs.length === 0 && fs.existsSync(path.join(dir, t, "README.md")), `${imgs.length} images`);
}

// Listing text limits (Unicode code points).
const listing = fs.readFileSync(path.join(dir, "google-play-listing-ar.md"), "utf8");
const block = (name) => listing.split(`<!-- ${name}:start -->`)[1].split(`<!-- ${name}:end -->`)[0].trim();
const len = (s) => [...s].length;
const shortLen = len(block("short"));
const fullLen = len(block("full"));
add("google-play-listing-ar.md", "app name ≤ 30", len("MAYTHA MARKET") <= 30, `${len("MAYTHA MARKET")} chars`);
add("google-play-listing-ar.md", "short description ≤ 80", shortLen > 0 && shortLen <= 80, `${shortLen} chars`);
add("google-play-listing-ar.md", "full description ≤ 4000", fullLen > 0 && fullLen <= 4000, `${fullLen} chars`);
for (const f of ["UPLOAD-GUIDE-AR.md", "optional-platform-assets/README.md"]) add(f, "exists", fs.existsSync(path.join(dir, f)), "");

const failed = rows.filter((r) => !r.ok);
const byFile = new Map();
for (const r of rows) byFile.set(r.file, [...(byFile.get(r.file) ?? []), r]);
let md = `# Validation report — Google Play assets\n\nGenerated by \`mobile/maytha_market/store/source/validate-assets.mjs\`.\n\n`;
md += `**Overall: ${failed.length === 0 ? "PASS" : `FAIL (${failed.length} failing checks)`}**\n\n`;
md += `| File | Result | Checks |\n|---|---|---|\n`;
for (const [file, rs] of byFile) {
  md += `| \`${file}\` | ${rs.every((r) => r.ok) ? "PASS" : "FAIL"} | ${rs.map((r) => `${r.ok ? "✓" : "✗"} ${r.check}${r.detail ? ` (${r.detail})` : ""}`).join("<br>")} |\n`;
}
md += `\n## Not covered by this script (manual)\n\n` +
  `- Every image was opened and reviewed visually: Arabic shaping/RTL, no clipping, no spinners or snackbars, no personal data.\n` +
  `- Phone captures are real Pixel 5 emulator screenshots (profile build, live catalog), in \`mobile/maytha_market/store/source/play-captures/\`; only the status bar is cropped (and screenshot 07 is a crop of the real cart's order section).\n` +
  `- Tablet: not produced — the app shows a stretched phone layout on a Pixel Tablet emulator (see tablet-*/README.md).\n` +
  `- Contact email for Play Console: missing (owner to provide).\n`;
fs.writeFileSync(path.join(dir, "VALIDATION-REPORT.md"), md);
console.log(md);
process.exit(failed.length ? 1 : 0);
